#!/usr/bin/env node
/**
 * Generates platform artefacts from tokens/tokens.json:
 *
 *   - web/src/styles/tokens.css                     CSS custom properties (light + dark)
 *   - web/src/generated/tokens.ts                   typed JS object
 *   - kit/src/commonMain/kotlin/com/strela/sui/tokens/GeneratedTokens.kt
 *
 * Usage: node scripts/generate-tokens.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(resolve(root, "tokens/tokens.json"), "utf8"));

const kebab = (value) =>
  value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d)/g, "$1-$2")
    .toLowerCase();

const write = (relativePath, contents) => {
  const target = resolve(root, relativePath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents, "utf8");
  console.log(`generated ${relativePath}`);
};

const colorNames = Object.keys(tokens.colors.light);

/* ------------------------------------------------------------------ CSS */
const colorBlock = (theme) =>
  colorNames
    .map((name) => `  --sui-color-${kebab(name)}: ${tokens.colors[theme][name]};`)
    .join("\n");

const typeBlock = Object.entries(tokens.typography)
  .flatMap(([name, value]) => [
    `  --sui-font-size-${kebab(name)}: ${value.fontSize}px;`,
    `  --sui-line-height-${kebab(name)}: ${value.lineHeight}px;`,
    `  --sui-font-weight-${kebab(name)}: ${value.fontWeight};`,
    `  --sui-letter-spacing-${kebab(name)}: ${value.letterSpacing}px;`,
  ])
  .join("\n");

const spacingBlock = Object.entries(tokens.spacing)
  .map(([name, value]) => `  --sui-space-${kebab(name)}: ${value}px;`)
  .join("\n");

const radiusBlock = Object.entries(tokens.radius)
  .map(([name, value]) => `  --sui-radius-${kebab(name)}: ${value}px;`)
  .join("\n");

write(
  "web/src/styles/tokens.css",
  `/* GENERATED by scripts/generate-tokens.mjs — do not edit by hand. */
:root,
[data-theme="light"] {
${colorBlock("light")}
}

[data-theme="dark"] {
${colorBlock("dark")}
}

:root {
${typeBlock}

${spacingBlock}

${radiusBlock}
}
`
);

/* -------------------------------------------------------------- TS object */
write(
  "web/src/generated/tokens.ts",
  `/* GENERATED by scripts/generate-tokens.mjs — do not edit by hand. */
export const tokens = ${JSON.stringify(
    {
      colors: tokens.colors,
      typography: tokens.typography,
      spacing: tokens.spacing,
      radius: tokens.radius,
    },
    null,
    2
  )} as const;

export type SuiColorName = keyof typeof tokens.colors.light;
export type SuiThemeName = keyof typeof tokens.colors;
`
);

/* ----------------------------------------------------------------- Kotlin */
const kotlinColor = (hex) => {
  const value = hex.replace("#", "").toUpperCase();
  if (value.length === 6) return `0xFF${value}L`;
  if (value.length === 8) {
    const [r, g, b, a] = [
      value.slice(0, 2),
      value.slice(2, 4),
      value.slice(4, 6),
      value.slice(6, 8),
    ];
    return `0x${a}${r}${g}${b}L`;
  }
  throw new Error(`Unsupported color format: ${hex}`);
};

const colorConstants = ["light", "dark"]
  .flatMap((theme) =>
    colorNames.map(
      (name) =>
        `    const val ${theme}${name[0].toUpperCase()}${name.slice(1)}: Long = ${kotlinColor(
          tokens.colors[theme][name]
        )}`
    )
  )
  .join("\n");

const typeConstants = Object.entries(tokens.typography)
  .flatMap(([name, value]) => {
    const prefix = `${name}${value.fontSize}`; // placeholder to keep shape obvious
    void prefix;
    return [
      `    const val ${name}FontSize: Float = ${value.fontSize}f`,
      `    const val ${name}LineHeight: Float = ${value.lineHeight}f`,
      `    const val ${name}FontWeight: Int = ${value.fontWeight}`,
      `    const val ${name}LetterSpacing: Float = ${value.letterSpacing}f`,
    ];
  })
  .join("\n");

const spacingConstants = Object.entries(tokens.spacing)
  .map(([name, value]) => `    const val ${name}: Int = ${value}`)
  .join("\n");

const radiusConstants = Object.entries(tokens.radius)
  .map(([name, value]) => `    const val ${name}: Int = ${value}`)
  .join("\n");

write(
  "kit/src/commonMain/kotlin/com/strela/sui/tokens/GeneratedTokens.kt",
  `// GENERATED by scripts/generate-tokens.mjs — do not edit by hand.
package com.strela.sui.tokens

internal object GeneratedColorTokens {
${colorConstants}
}

internal object GeneratedTypographyTokens {
${typeConstants}
}

internal object GeneratedSpacingTokens {
${spacingConstants}
}

internal object GeneratedRadiusTokens {
${radiusConstants}
}
`
);
